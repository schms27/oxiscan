//! Saving scan results as CSV, plain text, XML or an IP:Port list.

use crate::scanner::{format_ports, ScanResult};

pub const COLUMNS: [&str; 8] = [
    "IP",
    "Ping",
    "TTL",
    "Hostname",
    "Ports",
    "MAC Address",
    "NetBIOS Info",
    "Web detect",
];

pub fn cell(r: &ScanResult, col: usize) -> String {
    const NA: &str = "[n/a]";
    const NS: &str = "[n/s]";
    match col {
        0 => r.ip.to_string(),
        1 => r
            .ping_ms
            .map(|p| format!("{p} ms"))
            .unwrap_or_else(|| NA.into()),
        2 => r.ttl.map(|t| t.to_string()).unwrap_or_else(|| NA.into()),
        3 => match (&r.hostname, r.hostname_scanned) {
            (Some(h), _) => h.clone(),
            (None, true) => NA.into(),
            (None, false) => NS.into(),
        },
        4 => {
            if !r.ports_scanned {
                NS.into()
            } else if r.ports.is_empty() {
                NA.into()
            } else {
                format_ports(&r.ports)
            }
        }
        5 => opt(&r.mac, r.extra_scanned),
        6 => opt(&r.netbios, r.extra_scanned),
        7 => opt(&r.web, r.extra_scanned),
        _ => String::new(),
    }
}

fn opt(v: &Option<String>, scanned: bool) -> String {
    match v {
        Some(s) => s.clone(),
        None if scanned => "[n/a]".into(),
        None => "[n/s]".into(),
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Format {
    Csv,
    Txt,
    Xml,
    IpPort,
}

impl Format {
    pub fn from_path(path: &std::path::Path) -> Format {
        match path
            .extension()
            .and_then(|e| e.to_str())
            .map(|e| e.to_ascii_lowercase())
            .as_deref()
        {
            Some("csv") => Format::Csv,
            Some("xml") => Format::Xml,
            Some("lst") => Format::IpPort,
            _ => Format::Txt,
        }
    }
}

fn csv_escape(s: &str) -> String {
    if s.contains(',') || s.contains('"') || s.contains('\n') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

pub fn render(rows: &[&ScanResult], cols: &[usize], fmt: Format, scan_desc: &str) -> String {
    let mut out = String::new();
    match fmt {
        Format::Csv => {
            out.push_str(
                &cols
                    .iter()
                    .map(|c| csv_escape(COLUMNS[*c]))
                    .collect::<Vec<_>>()
                    .join(","),
            );
            out.push('\n');
            for r in rows {
                out.push_str(
                    &cols
                        .iter()
                        .map(|c| csv_escape(&cell(r, *c)))
                        .collect::<Vec<_>>()
                        .join(","),
                );
                out.push('\n');
            }
        }
        Format::Txt => {
            out.push_str("Generated by OxiScan\n");
            out.push_str(&format!("Scanned: {scan_desc}\n\n"));
            let widths: Vec<usize> = cols
                .iter()
                .map(|c| {
                    rows.iter()
                        .map(|r| cell(r, *c).chars().count())
                        .chain(std::iter::once(COLUMNS[*c].len()))
                        .max()
                        .unwrap_or(4)
                })
                .collect();
            let line = |vals: Vec<String>| {
                vals.iter()
                    .zip(&widths)
                    .map(|(v, w)| format!("{:<w$}", v, w = *w))
                    .collect::<Vec<_>>()
                    .join("  ")
                    .trim_end()
                    .to_string()
            };
            out.push_str(&line(
                cols.iter().map(|c| COLUMNS[*c].to_string()).collect(),
            ));
            out.push('\n');
            for r in rows {
                out.push_str(&line(cols.iter().map(|c| cell(r, *c)).collect()));
                out.push('\n');
            }
        }
        Format::Xml => {
            out.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
            out.push_str(&format!("<scan range=\"{}\">\n", xml_escape(scan_desc)));
            for r in rows {
                out.push_str(&format!(
                    "  <host address=\"{}\" alive=\"{}\">\n",
                    r.ip, r.alive
                ));
                for c in cols.iter().filter(|c| **c != 0) {
                    let tag = COLUMNS[*c].to_lowercase().replace(' ', "_");
                    out.push_str(&format!(
                        "    <{t}>{}</{t}>\n",
                        xml_escape(&cell(r, *c)),
                        t = tag
                    ));
                }
                out.push_str("  </host>\n");
            }
            out.push_str("</scan>\n");
        }
        Format::IpPort => {
            for r in rows {
                for p in &r.ports {
                    out.push_str(&format!("{}:{}\n", r.ip, p));
                }
            }
        }
    }
    out
}
